-- Extra columns: DB has a column, on an expected table, that isn't in ver5_tables.sql
-------------------------------------------------------------------------------
DECLARE extra_cols_cur CURSOR LOCAL FAST_FORWARD FOR
	SELECT t.name, c.name
	FROM sys.tables t
	JOIN sys.columns c ON c.object_id = t.object_id
	WHERE t.name IN (SELECT DISTINCT TableName FROM #ExpectedSchema)
	  AND NOT EXISTS (
		  SELECT 1 FROM #ExpectedSchema es
		  WHERE es.TableName = t.name AND es.ColumnName = c.name
	  )
	ORDER BY t.name, c.name;

OPEN extra_cols_cur;
FETCH NEXT FROM extra_cols_cur INTO @TableName, @ColumnName;
WHILE @@FETCH_STATUS = 0
BEGIN
	PRINT 'EXTRA COLUMN (not in ver5_tables.sql): ' + @TableName + '.' + @ColumnName;
	FETCH NEXT FROM extra_cols_cur INTO @TableName, @ColumnName;
END;
CLOSE extra_cols_cur;
DEALLOCATE extra_cols_cur;


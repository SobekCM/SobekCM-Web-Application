-- Mismatched columns: both sides have it, but type / length / nullability differ
-------------------------------------------------------------------------------
DECLARE @ExpType varchar(50), @ActType varchar(50), @ExpLen int, @ActLen int, @ExpNull bit, @ActNull bit;

DECLARE mismatch_cur CURSOR LOCAL FAST_FORWARD FOR
	SELECT
		es.TableName,
		es.ColumnName,
		es.DataType,
		ty.name,
		es.MaxLen,
		CASE WHEN c.max_length = -1 THEN -1
			 WHEN ty.name IN ('nvarchar','nchar') THEN c.max_length / 2
			 ELSE c.max_length END,
		es.IsNullable,
		c.is_nullable
	FROM #ExpectedSchema es
	JOIN sys.tables t ON t.name = es.TableName
	JOIN sys.columns c ON c.object_id = t.object_id AND c.name = es.ColumnName
	JOIN sys.types ty ON ty.user_type_id = c.user_type_id
	ORDER BY es.TableName, es.ColumnName;

OPEN mismatch_cur;
FETCH NEXT FROM mismatch_cur INTO @TableName, @ColumnName, @ExpType, @ActType, @ExpLen, @ActLen, @ExpNull, @ActNull;
WHILE @@FETCH_STATUS = 0
BEGIN
	IF @ExpType <> @ActType
		PRINT 'TYPE MISMATCH: ' + @TableName + '.' + @ColumnName + ' - expected [' + @ExpType + '] but found [' + @ActType + ']';

	IF @ExpLen IS NOT NULL AND (@ActLen IS NULL OR @ExpLen <> @ActLen)
		PRINT 'LENGTH MISMATCH: ' + @TableName + '.' + @ColumnName + ' - expected length '
			+ CASE WHEN @ExpLen = -1 THEN 'max' ELSE CAST(@ExpLen AS varchar(10)) END
			+ ' but found ' + CASE WHEN @ActLen = -1 THEN 'max' ELSE CAST(ISNULL(@ActLen,-2) AS varchar(10)) END;

	IF @ExpNull <> @ActNull
		PRINT 'NULLABILITY MISMATCH: ' + @TableName + '.' + @ColumnName + ' - expected '
			+ CASE WHEN @ExpNull = 1 THEN 'NULL' ELSE 'NOT NULL' END
			+ ' but found ' + CASE WHEN @ActNull = 1 THEN 'NULL' ELSE 'NOT NULL' END;

	FETCH NEXT FROM mismatch_cur INTO @TableName, @ColumnName, @ExpType, @ActType, @ExpLen, @ActLen, @ExpNull, @ActNull;
END;
CLOSE mismatch_cur;
DEALLOCATE mismatch_cur;

DROP TABLE #ExpectedSchema;


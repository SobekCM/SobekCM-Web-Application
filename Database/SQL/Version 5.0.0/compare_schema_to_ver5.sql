-- Missing columns: table exists, expected column doesn't
-------------------------------------------------------------------------------
DECLARE missing_cols_cur CURSOR LOCAL FAST_FORWARD FOR
	SELECT es.TableName, es.ColumnName
	FROM #ExpectedSchema es
	WHERE EXISTS (SELECT 1 FROM sys.tables t WHERE t.name = es.TableName)
	  AND NOT EXISTS (
		  SELECT 1
		  FROM sys.columns c
		  JOIN sys.tables t ON c.object_id = t.object_id
		  WHERE t.name = es.TableName AND c.name = es.ColumnName
	  )
	ORDER BY es.TableName, es.ColumnName;

OPEN missing_cols_cur;
FETCH NEXT FROM missing_cols_cur INTO @TableName, @ColumnName;
WHILE @@FETCH_STATUS = 0
BEGIN
	PRINT 'MISSING COLUMN: ' + @TableName + '.' + @ColumnName;
	FETCH NEXT FROM missing_cols_cur INTO @TableName, @ColumnName;
END;
CLOSE missing_cols_cur;
DEALLOCATE missing_cols_cur;

